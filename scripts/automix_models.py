#!/usr/bin/env python3
"""Verify Automix assets, generate bindings, or install a compatible Beat This! export."""

import argparse
import hashlib
import json
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "native/analyzer/model-manifest.json"
ASSET_DIRS = [ROOT / "app/src/main/assets", ROOT / "web/app/public/models"]
KOTLIN = ROOT / "shared/src/jvmSharedMain/kotlin/com/music/bitchord/playback/smart/AutomixModels.kt"
TYPESCRIPT = ROOT / "web/app/src/playback/automix/analysis/modelManifest.ts"


def digest(path):
    with path.open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def revision(manifest):
    return "/".join([
        f"beat-postprocessing-{manifest['postprocessingRevision']}",
        manifest["beat"]["sha256"], manifest["vocal"]["sha256"],
    ])


def bindings(manifest):
    kotlin = [
        "// Generated by python scripts/automix_models.py generate. Do not edit by hand.",
        "package com.music.bitchord.playback.smart", "", "object AutomixModels {",
        f'    const val ANALYSIS_REVISION = "{revision(manifest)}"',
    ]
    for key in ("beat", "vocal"):
        spec = manifest[key]
        shape = ", ".join(str(n) for n in spec["inputShape"])
        outputs = ", ".join(
            f'"{name}" to longArrayOf({", ".join(str(n) for n in dims)})'
            for name, dims in spec["outputs"].items()
        )
        kotlin += [
            f'    const val {key.upper()}_ASSET = "{spec["asset"]}"',
            f"    val {key.upper()} = ModelAsset(",
            f'        name = {key.upper()}_ASSET,',
            f'        bytes = {spec["bytes"]}L,',
            f'        sha256 = "{spec["sha256"]}",',
            f'        input = "{spec["input"]}",',
            f"        inputShape = longArrayOf({shape}),",
            f"        outputs = mapOf({outputs}),", "    )",
        ]
    kotlin += ["}", ""]
    typescript = (
        "// Generated by python scripts/automix_models.py generate. Do not edit by hand.\n"
        f"export const AUTOMIX_MODELS = {json.dumps(manifest, indent=2)} as const;\n"
        f"export const ANALYSIS_REVISION = {json.dumps(revision(manifest))};\n"
    )
    return {KOTLIN: "\n".join(kotlin), TYPESCRIPT: typescript}


def verify_manifest(manifest):
    if not isinstance(manifest["postprocessingRevision"], int) or manifest["postprocessingRevision"] < 1:
        raise ValueError("postprocessingRevision must be a positive integer")
    for key in ("beat", "vocal"):
        spec = manifest[key]
        if not re.fullmatch(r"[a-zA-Z0-9_.-]+\.onnx", spec["asset"]):
            raise ValueError(f"Invalid model filename: {spec['asset']}")
        if not re.fullmatch(r"[a-f0-9]{64}", spec["sha256"]) or spec["bytes"] <= 0:
            raise ValueError(f"Invalid checksum/length for {key}")
        if spec["license"] != "MIT":
            raise ValueError("The bundled checkpoints use the MIT model license")


def verify_graph(path, spec):
    try:
        import onnx
    except ImportError as error:
        raise RuntimeError("Graph checks need onnx: python -m pip install onnx") from error
    model = onnx.load(path)
    onnx.checker.check_model(model)

    def validate_value(value, expected, output=False):
        tensor = value.type.tensor_type
        shape = [dim.dim_value if dim.HasField("dim_value") else -1 for dim in tensor.shape.dim]
        matches = len(shape) == len(expected) and all(
            actual == wanted or (output and index == 0 and wanted == -1 and actual == 1)
            for index, (actual, wanted) in enumerate(zip(shape, expected))
        )
        if tensor.elem_type != onnx.TensorProto.FLOAT or not matches:
            raise ValueError(f"{value.name}: expected float32 {expected}, got {shape}")

    if [value.name for value in model.graph.input] != [spec["input"]]:
        raise ValueError("Unexpected model inputs")
    validate_value(model.graph.input[0], spec["inputShape"])
    outputs = {value.name: value for value in model.graph.output}
    if set(outputs) != set(spec["outputs"]):
        raise ValueError("Unexpected model outputs")
    for name, shape in spec["outputs"].items():
        validate_value(outputs[name], shape, output=True)
    if spec["input"] == "input_spectrogram" and any(node.op_type == "ConvInteger" for node in model.graph.node):
        raise ValueError("Beat This! convolutions must stay float; quantize only MatMul")


def write_bindings(manifest):
    for path, content in bindings(manifest).items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8", newline="\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    check = commands.add_parser("check", help="Verify both platforms' weights and generated bindings")
    check.add_argument("--onnx", action="store_true", help="Also validate ONNX graphs (requires onnx)")
    commands.add_parser("generate", help="Regenerate Kotlin/TypeScript bindings after a manifest change")
    install = commands.add_parser("install-beat", help="Install a tested MIT Beat This! ONNX export on both platforms")
    install.add_argument("model", type=Path)
    install.add_argument("--checkpoint", required=True, choices=[f"{kind}{seed}" for kind in ("final", "small") for seed in range(3)])
    vocal = commands.add_parser("install-vocal", help="Install a tested MIT Open-Unmix vocals export on both platforms")
    vocal.add_argument("model", type=Path)
    vocal.add_argument("--checkpoint", required=True, choices=["umx-vocals", "umxhq-vocals"])
    args = parser.parse_args()
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    verify_manifest(manifest)

    if args.command in ("install-beat", "install-vocal"):
        key = "beat" if args.command == "install-beat" else "vocal"
        source = args.model.resolve(strict=True)
        spec = dict(manifest[key])
        verify_graph(source, spec)
        checksum = digest(source)
        prefix = "beat_this" if key == "beat" else "vocals"
        checkpoint_name = args.checkpoint.replace("-", "_")
        spec.update(asset=f"{prefix}_{checkpoint_name}_q8_{checksum[:12]}.onnx",
                    checkpoint=args.checkpoint, sha256=checksum, bytes=source.stat().st_size)
        old_name = manifest[key]["asset"]
        # Validate everything before replacing the two bundled copies.
        for directory in ASSET_DIRS:
            destination = directory / spec["asset"]
            if source != destination.resolve():
                shutil.copyfile(source, destination)
        manifest[key] = spec
        MANIFEST.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8", newline="\n")
        write_bindings(manifest)
        if old_name != spec["asset"]:
            for directory in ASSET_DIRS:
                (directory / old_name).unlink(missing_ok=True)
        print(f"Installed {args.checkpoint}; analysis revision follows the weights' SHA-256")
    elif args.command == "generate":
        write_bindings(manifest)
        print("Generated Automix model bindings")
    else:
        for key in ("beat", "vocal"):
            spec = manifest[key]
            for directory in ASSET_DIRS:
                path = directory / spec["asset"]
                if path.stat().st_size != spec["bytes"] or digest(path) != spec["sha256"]:
                    raise ValueError(f"Model checksum mismatch: {path.relative_to(ROOT)}")
            if args.onnx:
                verify_graph(ASSET_DIRS[0] / spec["asset"], spec)
            print(f"{key}: matching SHA-256 on Android and web")
        for path, expected in bindings(manifest).items():
            if path.read_text(encoding="utf-8") != expected:
                raise ValueError(f"Stale bindings: {path.relative_to(ROOT)}; run generate")
        print("Model bindings match the manifest")


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError, KeyError, RuntimeError) as error:
        print(f"Automix models: {error}", file=sys.stderr)
        sys.exit(1)
