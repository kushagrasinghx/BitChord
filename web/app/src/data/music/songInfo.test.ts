import { describe, expect, it } from 'vitest';
import { compactCount, parseSongStats } from './songInfo';

describe('compactCount (SongInfoRepository.compactCount)', () => {
  it('shortens as YouTube does, truncating', () => {
    expect(compactCount('950')).toBe('950');
    expect(compactCount('1234')).toBe('1.2K');
    expect(compactCount('100000')).toBe('100K');
    expect(compactCount('2345678')).toBe('2.3M');
    expect(compactCount('999999')).toBe('999K');
    expect(compactCount('2000000000')).toBe('2B');
    expect(compactCount('n/a')).toBe('n/a');
  });
});

describe('parseSongStats', () => {
  const next = {
    contents: {
      twoColumnWatchNextResults: {
        results: {
          results: {
            contents: [
              {
                videoPrimaryInfoRenderer: {
                  viewCount: { videoViewCountRenderer: { originalViewCount: '2345678' } },
                  videoActions: { likeButtonViewModel: { toggleButtonViewModel: { buttonViewModel: { title: '12K' } } } },
                },
              },
              {
                videoSecondaryInfoRenderer: {
                  attributedDescription: { content: 'Provided to YouTube by X\n\nSong · Artist\n\nReleased on: 2021-03-05\n\nAuto-generated by YouTube.' },
                },
              },
              { itemSectionRenderer: { contents: [{ commentsEntryPointHeaderRenderer: { commentCount: { simpleText: '1.4K' } } }] } },
            ],
          },
        },
        // A recommendation's counts must not be read as the song's.
        secondaryResults: { videoPrimaryInfoRenderer: { viewCount: { videoViewCountRenderer: { originalViewCount: '5' } } } },
      },
    },
  };

  it('reads the views, likes, comments and release date of the video itself', () => {
    expect(parseSongStats(next)).toEqual({ releaseDate: '2021-03-05', views: '2.3M', likes: '12K', comments: '1.4K' });
  });

  it('leaves out what is not there', () => {
    expect(parseSongStats({})).toEqual({ releaseDate: null, views: null, likes: null, comments: null });
  });
});
